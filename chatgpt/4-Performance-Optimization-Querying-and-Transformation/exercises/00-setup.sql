-- More rows for inspection, not a production-scale benchmark.
CREATE OR REPLACE TABLE PERF_EVENTS AS
WITH NUMBERS AS (
  SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS N
  FROM TABLE(GENERATOR(ROWCOUNT => 100000))
)
SELECT N AS EVENT_ID,
  DATEADD('day',MOD(N - 1,30),'2026-01-01'::DATE) AS EVENT_DATE,
  MOD(N,1000) AS CUSTOMER_ID,
  (MOD(N,100) + 1)::NUMBER(12,2) AS AMOUNT
FROM NUMBERS ORDER BY EVENT_DATE, EVENT_ID;
