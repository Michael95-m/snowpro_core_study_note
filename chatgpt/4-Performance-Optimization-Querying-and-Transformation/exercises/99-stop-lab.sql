DECLARE
  LAB_WH_STATE STRING;
BEGIN
  SHOW WAREHOUSES LIKE 'D4_STUDY_WH';
  SELECT MAX("state") INTO :LAB_WH_STATE
    FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
  IF (LAB_WH_STATE = 'STARTED') THEN
    ALTER WAREHOUSE D4_STUDY_WH SUSPEND;
  END IF;
END;
$$;
