-- Objective 4.1. Run 00-setup.sql first. Use a fresh lab session.
USE ROLE SYSADMIN;
USE WAREHOUSE D4_STUDY_WH;
USE DATABASE D4_STUDY;
USE SCHEMA LAB;
ALTER SESSION SET QUERY_TAG = 'D4_DIAGNOSIS';
ALTER SESSION SET USE_CACHED_RESULT = FALSE;

SELECT SUM(AMOUNT) AS DAY_TOTAL
FROM PERF_EVENTS
WHERE EVENT_DATE >= '2026-01-10'::DATE AND EVENT_DATE < '2026-01-11'::DATE;
SET D4_QUERY_ID = LAST_QUERY_ID();
SELECT $D4_QUERY_ID AS INSPECT_THIS_QUERY;
-- Open that SELECT's Query Profile in Snowsight. Clients may submit background
-- queries; confirm the actual SQL/QUERY_TAG if the captured ID is unexpected.
SELECT OPERATOR_ID, OPERATOR_TYPE, OPERATOR_STATISTICS, EXECUTION_TIME_BREAKDOWN
FROM TABLE(GET_QUERY_OPERATOR_STATS($D4_QUERY_ID));
-- Requires MONITOR or OPERATE on the execution warehouse (ownership suffices).
-- Query must have completed and have operator statistics available.
-- There is no promised spill, speedup, or scanned-partition ratio in this lab.

-- Join correctness before warehouse sizing.
SELECT COUNT(*) AS CARTESIAN_ROWS FROM ORDERS CROSS JOIN CUSTOMERS;
-- Expected: 24 (6 orders x 4 customers).
SELECT COUNT(*) AS CORRECT_ROWS, SUM(O.AMOUNT) AS TOTAL
FROM ORDERS O JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID;
-- Expected: 6 / 750.
SELECT COUNT(*) AS DUPLICATED_ROWS, SUM(O.AMOUNT) AS WRONG_TOTAL
FROM ORDERS O JOIN CUSTOMER_VERSIONS C ON O.CUSTOMER_ID = C.CUSTOMER_ID;
-- Expected: 8 / 900. A join condition alone does not fix duplicate dimension keys.
WITH LATEST_CUSTOMER AS (
  SELECT * FROM CUSTOMER_VERSIONS
  QUALIFY ROW_NUMBER() OVER (
    PARTITION BY CUSTOMER_ID ORDER BY UPDATED_AT DESC, CUSTOMER_NAME
  ) = 1
)
SELECT COUNT(*) AS CORRECT_ROWS, SUM(O.AMOUNT) AS CORRECT_TOTAL
FROM ORDERS O JOIN LATEST_CUSTOMER C ON O.CUSTOMER_ID = C.CUSTOMER_ID;
-- Expected: 6 / 750. Verify the correct business grain before optimizing.

SELECT QUERY_ID, QUERY_TAG, QUERY_TEXT,
  EXECUTION_TIME / 1000.0 AS EXECUTION_SECONDS,
  QUEUED_OVERLOAD_TIME / 1000.0 AS OVERLOAD_SECONDS,
  QUEUED_PROVISIONING_TIME / 1000.0 AS PROVISIONING_SECONDS,
  TRANSACTION_BLOCKED_TIME / 1000.0 AS BLOCKED_SECONDS,
  PARTITIONS_SCANNED, PARTITIONS_TOTAL,
  BYTES_SPILLED_TO_LOCAL_STORAGE, BYTES_SPILLED_TO_REMOTE_STORAGE
FROM TABLE(D4_STUDY.INFORMATION_SCHEMA.QUERY_HISTORY_BY_SESSION(RESULT_LIMIT => 100))
ORDER BY START_TIME DESC;
-- Most queue/spill values may be zero. Read symptoms; do not manufacture load.
-- ACCOUNT_USAGE.QUERY_HISTORY is useful for longer history but has latency.
ALTER SESSION UNSET USE_CACHED_RESULT;
ALTER SESSION UNSET QUERY_TAG;
UNSET D4_QUERY_ID;
