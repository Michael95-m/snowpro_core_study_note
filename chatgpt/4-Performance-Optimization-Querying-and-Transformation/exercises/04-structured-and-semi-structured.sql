WITH SAMPLE (ID, VAL) AS (SELECT * FROM VALUES (1,10),(2,NULL),(3,10),(4,20))
SELECT COUNT(*) AS ROW_COUNT, COUNT(VAL) AS NON_NULL_VALUES,
  COUNT(DISTINCT VAL) AS DISTINCT_NON_NULL_VALUES, AVG(VAL) AS AVERAGE_VALUE
FROM SAMPLE;
-- Expected: 4 / 3 / 2 / approximately 13.333333.
WITH SCORES (ID, SCORE) AS (SELECT * FROM VALUES (1,100),(2,100),(3,90))
SELECT ID, SCORE,
  ROW_NUMBER() OVER (ORDER BY SCORE DESC, ID) AS ROW_NUM,
  RANK() OVER (ORDER BY SCORE DESC) AS COMPETITION_RANK,
  DENSE_RANK() OVER (ORDER BY SCORE DESC) AS DENSE_RANKING
FROM SCORES ORDER BY ID;
-- ROW_NUM: 1,2,3. RANK: 1,1,3. DENSE_RANK: 1,1,2.
WITH EVENTS (ID, EVENT_DATE, AMOUNT) AS (
  SELECT COLUMN1, COLUMN2::DATE, COLUMN3 FROM VALUES
    (1,'2026-01-01',10),(2,'2026-01-01',20),(3,'2026-01-02',5)
)
SELECT ID,
  SUM(AMOUNT) OVER (ORDER BY EVENT_DATE, ID
    ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS ROWS_TOTAL,
  SUM(AMOUNT) OVER (ORDER BY EVENT_DATE
    RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS RANGE_TOTAL
FROM EVENTS ORDER BY ID;
-- ROWS_TOTAL: 10,30,35. RANGE_TOTAL: 30,30,35 (same-date peers included).

