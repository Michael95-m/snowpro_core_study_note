USE ROLE SYSADMIN;
USE WAREHOUSE D5_STUDY_WH;
USE DATABASE D5_STUDY;
USE SCHEMA LAB;

CREATE OR REPLACE TABLE D5_PARTNER_ORDERS (
  ORDER_ID NUMBER NOT NULL,
  REGION STRING,
  AMOUNT NUMBER(12, 2),
  APPROVED_FOR_SHARE BOOLEAN,
  INTERNAL_NOTE STRING
);

INSERT INTO D5_PARTNER_ORDERS VALUES
  (1, 'APAC', 100, TRUE, 'synthetic internal note A'),
  (2, 'EMEA', 200, FALSE, 'synthetic internal note B'),
  (3, 'APAC', 300, TRUE, 'synthetic internal note C');

CREATE OR REPLACE SECURE VIEW D5_PARTNER_ORDERS_V AS
SELECT ORDER_ID, REGION, AMOUNT
FROM D5_PARTNER_ORDERS
WHERE APPROVED_FOR_SHARE;

SELECT ORDER_ID, REGION, AMOUNT FROM D5_PARTNER_ORDERS_V ORDER BY ORDER_ID;
SELECT COUNT(*) AS SHARED_ROWS, SUM(AMOUNT) AS SHARED_TOTAL
FROM D5_PARTNER_ORDERS_V;
