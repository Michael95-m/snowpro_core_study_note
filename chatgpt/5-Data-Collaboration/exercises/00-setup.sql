-- Domain 5 uses a dedicated database and warehouse for synthetic study data.
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS D5_STUDY_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS D5_STUDY;
CREATE SCHEMA IF NOT EXISTS D5_STUDY.LAB;

USE WAREHOUSE D5_STUDY_WH;
USE DATABASE D5_STUDY;
USE SCHEMA LAB;

SELECT CURRENT_DATABASE() AS LAB_DATABASE, CURRENT_SCHEMA() AS LAB_SCHEMA,
       CURRENT_WAREHOUSE() AS LAB_WAREHOUSE;
