-- A standard table clone starts from the current snapshot.
USE ROLE SYSADMIN;
USE WAREHOUSE D5_STUDY_WH;
USE DATABASE D5_STUDY;
USE SCHEMA LAB;

CREATE OR REPLACE TABLE D5_CLONE_SOURCE (
  ORDER_ID NUMBER NOT NULL,
  AMOUNT NUMBER(12, 2)
);

INSERT INTO D5_CLONE_SOURCE VALUES (1, 100), (2, 200);

CREATE OR REPLACE TABLE D5_CLONE_SANDBOX CLONE D5_CLONE_SOURCE;

SELECT 'SOURCE' AS OBJECT_LABEL, COUNT(*) AS ROWS_FOUND, SUM(AMOUNT) AS TOTAL
FROM D5_CLONE_SOURCE
UNION ALL
SELECT 'CLONE', COUNT(*), SUM(AMOUNT) FROM D5_CLONE_SANDBOX
ORDER BY OBJECT_LABEL;
-- Expected: 2 / 300 for each table.

UPDATE D5_CLONE_SOURCE SET AMOUNT = 250 WHERE ORDER_ID = 2;
INSERT INTO D5_CLONE_SANDBOX VALUES (3, 25);

SELECT 'SOURCE' AS OBJECT_LABEL, COUNT(*) AS ROWS_FOUND, SUM(AMOUNT) AS TOTAL
FROM D5_CLONE_SOURCE
UNION ALL
SELECT 'CLONE', COUNT(*), SUM(AMOUNT) FROM D5_CLONE_SANDBOX
ORDER BY OBJECT_LABEL;
-- Expected: CLONE 3 / 325, SOURCE 2 / 350.

