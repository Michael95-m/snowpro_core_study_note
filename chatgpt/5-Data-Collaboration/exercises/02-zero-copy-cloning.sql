-- A standard table clone starts from the current snapshot.
USE ROLE SYSADMIN;
USE WAREHOUSE D5_STUDY_WH;
USE DATABASE D5_STUDY;
USE SCHEMA LAB;

CREATE OR REPLACE TABLE D5_CLONE_SOURCE (
  ORDER_ID NUMBER NOT NULL,
  AMOUNT NUMBER(12, 2)
);

INSERT INTO D5_CLONE_SOURCE VALUES (1, 100), (2, 200);

CREATE OR REPLACE TABLE D5_CLONE_SANDBOX CLONE D5_CLONE_SOURCE;

SELECT 'SOURCE' AS OBJECT_LABEL, COUNT(*) AS ROWS_FOUND, SUM(AMOUNT) AS TOTAL
FROM D5_CLONE_SOURCE
UNION ALL
SELECT 'CLONE', COUNT(*), SUM(AMOUNT) FROM D5_CLONE_SANDBOX
ORDER BY OBJECT_LABEL;
-- Expected: 2 / 300 for each table.

UPDATE D5_CLONE_SOURCE SET AMOUNT = 250 WHERE ORDER_ID = 2;
INSERT INTO D5_CLONE_SANDBOX VALUES (3, 25);

SELECT 'SOURCE' AS OBJECT_LABEL, COUNT(*) AS ROWS_FOUND, SUM(AMOUNT) AS TOTAL
FROM D5_CLONE_SOURCE
UNION ALL
SELECT 'CLONE', COUNT(*), SUM(AMOUNT) FROM D5_CLONE_SANDBOX
ORDER BY OBJECT_LABEL;
-- Expected: CLONE 3 / 325, SOURCE 2 / 350.

-- Compare explicit source grants with future grants in the destination.
-- SYSADMIN owns this managed access schema and can define its future grants.
CREATE SCHEMA IF NOT EXISTS D5_STUDY.CLONE_GRANT_LAB WITH MANAGED ACCESS;
CREATE DATABASE ROLE IF NOT EXISTS D5_STUDY.CLONE_SOURCE_READER;
CREATE DATABASE ROLE IF NOT EXISTS D5_STUDY.CLONE_FUTURE_READER;

GRANT SELECT ON TABLE D5_STUDY.LAB.D5_CLONE_SOURCE
  TO DATABASE ROLE D5_STUDY.CLONE_SOURCE_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA D5_STUDY.CLONE_GRANT_LAB
  TO DATABASE ROLE D5_STUDY.CLONE_FUTURE_READER;

-- Start with new clones on each run so the comparison uses creation rules.
DROP TABLE IF EXISTS D5_STUDY.CLONE_GRANT_LAB.CLONE_WITH_GRANTS;
DROP TABLE IF EXISTS D5_STUDY.CLONE_GRANT_LAB.CLONE_WITHOUT_GRANTS;

CREATE TABLE D5_STUDY.CLONE_GRANT_LAB.CLONE_WITH_GRANTS
  CLONE D5_STUDY.LAB.D5_CLONE_SOURCE COPY GRANTS;
CREATE TABLE D5_STUDY.CLONE_GRANT_LAB.CLONE_WITHOUT_GRANTS
  CLONE D5_STUDY.LAB.D5_CLONE_SOURCE;

SHOW GRANTS ON TABLE D5_STUDY.CLONE_GRANT_LAB.CLONE_WITH_GRANTS;
-- Expected SELECT among these two roles: CLONE_SOURCE_READER.
SHOW GRANTS ON TABLE D5_STUDY.CLONE_GRANT_LAB.CLONE_WITHOUT_GRANTS;
-- Expected SELECT among these two roles: CLONE_FUTURE_READER.

