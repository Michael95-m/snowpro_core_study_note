-- Run after 00-setup.sql. Use one session and leave AUTOCOMMIT enabled.
USE ROLE SYSADMIN;
USE WAREHOUSE D5_STUDY_WH;
USE DATABASE D5_STUDY;
USE SCHEMA LAB;

CREATE OR REPLACE TABLE D5_RECOVERY_ORDERS (
  ORDER_ID NUMBER NOT NULL,
  AMOUNT NUMBER(12, 2)
) DATA_RETENTION_TIME_IN_DAYS = 1;

INSERT INTO D5_RECOVERY_ORDERS VALUES (1, 100), (2, 200), (3, 300);

-- Run the DELETE and the next SELECT back to back, with no intervening query.
DELETE FROM D5_RECOVERY_ORDERS WHERE ORDER_ID = 2;

SELECT COUNT(*) AS HISTORICAL_ROWS, SUM(AMOUNT) AS HISTORICAL_TOTAL
FROM D5_RECOVERY_ORDERS BEFORE (STATEMENT => LAST_QUERY_ID());
-- Expected: 3 / 600. If needed, substitute the quoted DELETE query ID from Query History.

SELECT COUNT(*) AS CURRENT_ROWS, SUM(AMOUNT) AS CURRENT_TOTAL
FROM D5_RECOVERY_ORDERS;
-- Expected: 2 / 400.

