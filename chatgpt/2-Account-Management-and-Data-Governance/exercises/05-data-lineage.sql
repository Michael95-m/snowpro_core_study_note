-- Optional Domain 2 lineage lab. Run 00-setup.sql first.
-- GET_LINEAGE requires Enterprise Edition or higher, VIEW LINEAGE on the
-- account, and access to the objects. PUBLIC has VIEW LINEAGE by default,
-- unless your account administrator revoked that default grant.
USE ROLE SYSADMIN;
USE WAREHOUSE D2_STUDY_WH;
USE DATABASE D2_STUDY;
USE SCHEMA LAB;

-- Make a short, deterministic movement chain from the existing ORDERS table.
CREATE OR REPLACE TABLE D2_STUDY.LAB.LINEAGE_CLEAN_ORDERS AS
SELECT ORDER_ID, AMOUNT
FROM D2_STUDY.LAB.ORDERS
WHERE AMOUNT > 0;

CREATE OR REPLACE TABLE D2_STUDY.LAB.LINEAGE_ORDER_TOTAL AS
SELECT SUM(AMOUNT) AS TOTAL_AMOUNT
FROM D2_STUDY.LAB.LINEAGE_CLEAN_ORDERS;

SELECT TOTAL_AMOUNT FROM D2_STUDY.LAB.LINEAGE_ORDER_TOTAL;
-- Expected from the setup fixture: 350.

-- In Enterprise+, expect an ORDERS -> CLEAN -> TOTAL downstream chain.
-- Capture may take time; an empty lineage result is not a failed CTAS.
SELECT DISTANCE, SOURCE_OBJECT_NAME, TARGET_OBJECT_NAME, PROCESS
FROM TABLE(SNOWFLAKE.CORE.GET_LINEAGE(
  'D2_STUDY.LAB.ORDERS', 'TABLE', 'DOWNSTREAM', 2
))
ORDER BY DISTANCE, SOURCE_OBJECT_NAME, TARGET_OBJECT_NAME;

-- Reverse the question: where did the summary come from?
SELECT DISTANCE, SOURCE_OBJECT_NAME, TARGET_OBJECT_NAME
FROM TABLE(SNOWFLAKE.CORE.GET_LINEAGE(
  'D2_STUDY.LAB.LINEAGE_ORDER_TOTAL', 'TABLE', 'UPSTREAM', 2
))
ORDER BY DISTANCE, SOURCE_OBJECT_NAME;

