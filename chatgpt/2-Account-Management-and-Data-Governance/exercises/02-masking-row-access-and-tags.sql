-- Objective 2.2. Enterprise+ and 00-setup.sql are required for this whole file.
-- Policy bodies use account roles deliberately; run role tests with secondaries
-- disabled. A broad administrative role is not a restricted-reader test.
USE ROLE SYSADMIN;
USE SECONDARY ROLES NONE;
USE WAREHOUSE D2_STUDY_WH;
USE DATABASE D2_STUDY;
USE SCHEMA LAB;
-- Reset only this synthetic fixture. COPY GRANTS preserves reader grants;
-- replacing the table removes its previous policy assignments and history.
CREATE OR REPLACE TABLE CUSTOMERS COPY GRANTS AS
SELECT COLUMN1::NUMBER AS CUSTOMER_ID, COLUMN2::STRING AS REGION,
  COLUMN3::STRING AS EMAIL
FROM VALUES (1,'APAC','alice@example.test'),(2,'APAC','bob@example.test'),
  (3,'EMEA','cara@example.test');
CREATE OR REPLACE MASKING POLICY D2_STUDY.POLICIES.EMAIL_MASK
  AS (VAL STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('D2_STUDY_FULL_ACCESS') THEN VAL
       ELSE '***MASKED***' END;
CREATE OR REPLACE ROW ACCESS POLICY D2_STUDY.POLICIES.REGION_FILTER
  AS (ROW_REGION STRING) RETURNS BOOLEAN ->
    IS_ROLE_IN_SESSION('D2_STUDY_FULL_ACCESS')
    OR (IS_ROLE_IN_SESSION('D2_STUDY_APAC') AND ROW_REGION = 'APAC');
ALTER TABLE CUSTOMERS MODIFY COLUMN EMAIL
  SET MASKING POLICY D2_STUDY.POLICIES.EMAIL_MASK;
ALTER TABLE CUSTOMERS ADD ROW ACCESS POLICY D2_STUDY.POLICIES.REGION_FILTER
  ON (REGION);

USE ROLE D2_STUDY_APAC;
SELECT * FROM D2_STUDY.LAB.CUSTOMERS ORDER BY CUSTOMER_ID;
-- Expected: IDs 1 and 2 only; both emails are ***MASKED***.
USE ROLE D2_STUDY_FULL_ACCESS;
SELECT * FROM D2_STUDY.LAB.CUSTOMERS ORDER BY CUSTOMER_ID;
-- Expected: all 3 IDs with original synthetic emails.
USE ROLE D2_STUDY_ANALYST;
SELECT COUNT(*) AS VISIBLE_ROWS FROM D2_STUDY.LAB.CUSTOMERS;
-- Expected: 0. SELECT privilege exists, but the row policy permits no rows.

USE ROLE SYSADMIN;
CREATE TAG IF NOT EXISTS D2_STUDY.POLICIES.CLASSIFICATION
  ALLOWED_VALUES 'PUBLIC', 'INTERNAL', 'PII';
ALTER TABLE CUSTOMERS MODIFY COLUMN EMAIL
  SET TAG D2_STUDY.POLICIES.CLASSIFICATION = 'PII';
SELECT SYSTEM$GET_TAG('D2_STUDY.POLICIES.CLASSIFICATION',
  'D2_STUDY.LAB.CUSTOMERS.EMAIL','COLUMN') AS CLASSIFICATION;
-- Expected: PII. This tag is a label; no masking policy is attached to the tag.
SELECT * FROM TABLE(D2_STUDY.INFORMATION_SCHEMA.POLICY_REFERENCES(
  REF_ENTITY_NAME => 'D2_STUDY.LAB.CUSTOMERS', REF_ENTITY_DOMAIN => 'TABLE'
));

-- Unset before dropping/replacing a referenced masking policy.
ALTER TABLE CUSTOMERS MODIFY COLUMN EMAIL UNSET MASKING POLICY;
USE ROLE D2_STUDY_APAC;
SELECT * FROM D2_STUDY.LAB.CUSTOMERS ORDER BY CUSTOMER_ID;
-- Expected: still 2 rows, now original emails. The tag alone does not mask them.
USE ROLE SYSADMIN;
DROP MASKING POLICY D2_STUDY.POLICIES.EMAIL_MASK;
CREATE MASKING POLICY D2_STUDY.POLICIES.EMAIL_MASK
  AS (VAL STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('D2_STUDY_FULL_ACCESS') THEN VAL
       ELSE '***MASKED***' END;
ALTER TABLE CUSTOMERS MODIFY COLUMN EMAIL
  SET MASKING POLICY D2_STUDY.POLICIES.EMAIL_MASK;
-- Protection is restored on the lab column. No real PII is in these fixtures.
USE SECONDARY ROLES ALL;
