-- Objective 2.1. Run 00-setup.sql first. No account/user login rules change.
USE SECONDARY ROLES NONE;
USE ROLE D2_STUDY_ANALYST;
USE WAREHOUSE D2_STUDY_WH;
USE DATABASE D2_STUDY;
USE SCHEMA LAB;
SELECT CURRENT_ROLE(), IS_ROLE_IN_SESSION('D2_STUDY_READER') AS INHERITS_READER;
-- Expected: D2_STUDY_ANALYST / TRUE.
SELECT COUNT(*) AS ORDER_COUNT, SUM(AMOUNT) AS TOTAL FROM ORDERS;
-- Expected: 3 / 350. The parent analyst role inherits the reader role's grants.
SHOW GRANTS TO ROLE D2_STUDY_READER;

USE ROLE SYSADMIN;
CREATE DATABASE ROLE IF NOT EXISTS D2_STUDY.LAB_READER;
GRANT USAGE ON SCHEMA D2_STUDY.LAB TO DATABASE ROLE D2_STUDY.LAB_READER;
GRANT SELECT ON TABLE D2_STUDY.LAB.ORDERS TO DATABASE ROLE D2_STUDY.LAB_READER;
GRANT DATABASE ROLE D2_STUDY.LAB_READER TO ROLE D2_STUDY_DB_USER;
GRANT USAGE ON WAREHOUSE D2_STUDY_WH TO ROLE D2_STUDY_DB_USER;
USE ROLE D2_STUDY_DB_USER;
SELECT COUNT(*) FROM D2_STUDY.LAB.ORDERS;
-- Expected: 3. Database-role access arrives through the active account role.
-- Warehouse access is an account-role grant, outside the database role's scope.
-- Do not try USE ROLE D2_STUDY.LAB_READER; it is not a directly active role.

-- Existing grants versus future grants: a separate, isolated consumer role.
USE ROLE SYSADMIN;
GRANT USAGE ON DATABASE D2_STUDY TO ROLE D2_STUDY_FUTURE_READER;
GRANT USAGE ON SCHEMA D2_STUDY.LAB TO ROLE D2_STUDY_FUTURE_READER;
GRANT USAGE ON WAREHOUSE D2_STUDY_WH TO ROLE D2_STUDY_FUTURE_READER;
-- Reset this lab demonstration when rerunning the file.
DROP TABLE IF EXISTS D2_STUDY.LAB.CREATED_AFTER_ALL;
DROP TABLE IF EXISTS D2_STUDY.LAB.CREATED_AFTER_FUTURE;
REVOKE SELECT ON FUTURE TABLES IN SCHEMA D2_STUDY.LAB
  FROM ROLE D2_STUDY_FUTURE_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA D2_STUDY.LAB
  TO ROLE D2_STUDY_FUTURE_READER;
CREATE TABLE D2_STUDY.LAB.CREATED_AFTER_ALL (ID NUMBER);
INSERT INTO D2_STUDY.LAB.CREATED_AFTER_ALL VALUES (1);
GRANT SELECT ON FUTURE TABLES IN SCHEMA D2_STUDY.LAB
  TO ROLE D2_STUDY_FUTURE_READER;
CREATE TABLE D2_STUDY.LAB.CREATED_AFTER_FUTURE (ID NUMBER);
INSERT INTO D2_STUDY.LAB.CREATED_AFTER_FUTURE VALUES (2);
USE ROLE D2_STUDY_FUTURE_READER;
SELECT * FROM D2_STUDY.LAB.CREATED_AFTER_FUTURE;
-- Expected: 2. Future grants apply at object creation time.
-- Intentional failure; run separately rather than as part of the full script:
-- SELECT * FROM D2_STUDY.LAB.CREATED_AFTER_ALL;
-- Granting FUTURE did not backfill that table; earlier ALL predated its creation.
USE ROLE SYSADMIN;
GRANT SELECT ON ALL TABLES IN SCHEMA D2_STUDY.LAB
  TO ROLE D2_STUDY_FUTURE_READER;
USE ROLE D2_STUDY_FUTURE_READER;
SELECT * FROM D2_STUDY.LAB.CREATED_AFTER_ALL;
-- Expected: 1, after the explicit backfill.

