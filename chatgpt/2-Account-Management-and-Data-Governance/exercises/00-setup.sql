-- Domain 2. Fresh lab session recommended. No real customer data or new users.
-- ACCOUNTADMIN is used for this one-time lab delegation; ordinary work below
-- switches to SYSADMIN and purpose-specific roles. No account policies change.
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS D2_STUDY_READER;
CREATE ROLE IF NOT EXISTS D2_STUDY_ANALYST;
CREATE ROLE IF NOT EXISTS D2_STUDY_APAC;
CREATE ROLE IF NOT EXISTS D2_STUDY_FULL_ACCESS;
CREATE ROLE IF NOT EXISTS D2_STUDY_DB_USER;
CREATE ROLE IF NOT EXISTS D2_STUDY_FUTURE_READER;
GRANT ROLE D2_STUDY_READER TO ROLE D2_STUDY_ANALYST;
GRANT ROLE D2_STUDY_READER TO ROLE D2_STUDY_APAC;
GRANT ROLE D2_STUDY_READER TO ROLE D2_STUDY_FULL_ACCESS;
GRANT ROLE D2_STUDY_ANALYST TO ROLE SYSADMIN;
GRANT ROLE D2_STUDY_APAC TO ROLE SYSADMIN;
GRANT ROLE D2_STUDY_FULL_ACCESS TO ROLE SYSADMIN;
GRANT ROLE D2_STUDY_DB_USER TO ROLE SYSADMIN;
GRANT ROLE D2_STUDY_FUTURE_READER TO ROLE SYSADMIN;
-- Quote the identifier so mixed-case/email-style user names also work.
SET D2_LEARNER = '"' || REPLACE(CURRENT_USER(), '"', '""') || '"';
GRANT ROLE D2_STUDY_ANALYST TO USER IDENTIFIER($D2_LEARNER);
GRANT ROLE D2_STUDY_APAC TO USER IDENTIFIER($D2_LEARNER);
GRANT ROLE D2_STUDY_FULL_ACCESS TO USER IDENTIFIER($D2_LEARNER);
GRANT ROLE D2_STUDY_DB_USER TO USER IDENTIFIER($D2_LEARNER);
GRANT ROLE D2_STUDY_FUTURE_READER TO USER IDENTIFIER($D2_LEARNER);
UNSET D2_LEARNER;

USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS D2_STUDY_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  ENABLE_QUERY_ACCELERATION = FALSE;
CREATE DATABASE IF NOT EXISTS D2_STUDY;
CREATE SCHEMA IF NOT EXISTS D2_STUDY.LAB;
CREATE SCHEMA IF NOT EXISTS D2_STUDY.POLICIES;
CREATE SCHEMA IF NOT EXISTS D2_STUDY.MANAGED WITH MANAGED ACCESS;
USE WAREHOUSE D2_STUDY_WH;
USE DATABASE D2_STUDY;
USE SCHEMA LAB;
CREATE OR REPLACE TABLE ORDERS (ORDER_ID NUMBER, REGION STRING, AMOUNT NUMBER);
INSERT INTO ORDERS VALUES (1,'APAC',100),(2,'APAC',50),(3,'EMEA',200);
CREATE OR REPLACE TABLE CUSTOMERS (
  CUSTOMER_ID NUMBER, REGION STRING, EMAIL STRING
);
INSERT INTO CUSTOMERS VALUES
  (1,'APAC','alice@example.test'),
  (2,'APAC','bob@example.test'),
  (3,'EMEA','cara@example.test');
GRANT USAGE ON DATABASE D2_STUDY TO ROLE D2_STUDY_READER;
GRANT USAGE ON SCHEMA D2_STUDY.LAB TO ROLE D2_STUDY_READER;
GRANT USAGE ON WAREHOUSE D2_STUDY_WH TO ROLE D2_STUDY_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA D2_STUDY.LAB TO ROLE D2_STUDY_READER;
SELECT COUNT(*) AS CUSTOMER_COUNT FROM CUSTOMERS;
