-- Run in SHARE_LAB. Replace PROVIDER_LOCATOR with the main account's locator.
USE ROLE ACCOUNTADMIN;

SELECT CURRENT_ACCOUNT_NAME() AS CONSUMER_ACCOUNT,
       CURRENT_REGION() AS CONSUMER_REGION;
SHOW SHARES;

CREATE DATABASE UD_IMPORTED_FILES
  FROM SHARE PROVIDER_LOCATOR.UD_LAB_FILES_SHARE;

-- Select a consumer warehouse before running these queries.
SELECT RELATIVE_PATH, SIZE, SCOPED_FILE_URL
FROM UD_IMPORTED_FILES.LAB.PARTNER_FILES_V;
-- Expected: one row for partner-brief.txt. Open SCOPED_FILE_URL from your own results.

SELECT COUNT(*) AS INTERNAL_FILES_VISIBLE
FROM UD_IMPORTED_FILES.LAB.PARTNER_FILES_V
WHERE RELATIVE_PATH = 'internal-draft.txt';
-- Expected: 0.
