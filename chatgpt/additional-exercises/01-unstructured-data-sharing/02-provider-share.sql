USE ROLE ACCOUNTADMIN;

ALTER STAGE UD_SHARE_STUDY.LAB.DOCS_STAGE REFRESH;

SELECT RELATIVE_PATH, SIZE, LAST_MODIFIED
FROM DIRECTORY(@UD_SHARE_STUDY.LAB.DOCS_STAGE)
ORDER BY RELATIVE_PATH;
-- Expected: internal-draft.txt and partner-brief.txt.

CREATE SECURE VIEW UD_SHARE_STUDY.LAB.PARTNER_FILES_V AS
SELECT RELATIVE_PATH, SIZE,
       BUILD_SCOPED_FILE_URL(@UD_SHARE_STUDY.LAB.DOCS_STAGE, RELATIVE_PATH) AS SCOPED_FILE_URL
FROM DIRECTORY(@UD_SHARE_STUDY.LAB.DOCS_STAGE)
WHERE RELATIVE_PATH = 'partner-brief.txt';

SELECT RELATIVE_PATH FROM UD_SHARE_STUDY.LAB.PARTNER_FILES_V;
-- Expected: partner-brief.txt only. Check this before adding the consumer.

CREATE SHARE UD_LAB_FILES_SHARE;
GRANT USAGE ON DATABASE UD_SHARE_STUDY TO SHARE UD_LAB_FILES_SHARE;
GRANT USAGE ON SCHEMA UD_SHARE_STUDY.LAB TO SHARE UD_LAB_FILES_SHARE;
GRANT SELECT ON VIEW UD_SHARE_STUDY.LAB.PARTNER_FILES_V TO SHARE UD_LAB_FILES_SHARE;
ALTER SHARE UD_LAB_FILES_SHARE ADD ACCOUNTS = MY_ORG.SHARE_LAB;

SHOW GRANTS TO SHARE UD_LAB_FILES_SHARE;
