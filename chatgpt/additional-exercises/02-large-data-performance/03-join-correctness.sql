USE ROLE SYSADMIN;
USE WAREHOUSE PERF_LAB_WH;
USE DATABASE PERF_LAB;
USE SCHEMA LAB;

CREATE OR REPLACE TABLE CUSTOMER_VERSIONS AS
WITH CUSTOMER_IDS AS (
  SELECT ROW_NUMBER() OVER (ORDER BY SEQ8()) AS CUSTOMER_ID
  FROM TABLE(GENERATOR(ROWCOUNT => 10000))
),
PERIODS AS (
  SELECT COLUMN1::DATE AS VALID_FROM,
         COLUMN2::DATE AS VALID_TO,
         COLUMN3::STRING AS REGION
  FROM VALUES
    ('2025-01-01', '2025-07-01', 'WEST'),
    ('2025-07-01', '2026-01-01', 'EAST')
)
SELECT CUSTOMER_ID, VALID_FROM, VALID_TO, REGION
FROM CUSTOMER_IDS CROSS JOIN PERIODS;

ALTER SESSION SET USE_CACHED_RESULT = FALSE;
ALTER SESSION SET QUERY_TAG = 'PERF_LAB_JOIN';

-- Baseline for one week, before joining.
SELECT COUNT(*) AS EVENT_COUNT, SUM(AMOUNT) AS TOTAL
FROM EVENTS_BY_DATE
WHERE EVENT_DATE >= DATE '2025-01-01' AND EVENT_DATE < DATE '2025-01-08';

-- ID-only join. Each sale matches both customer versions.
SELECT COUNT(*) AS JOINED_ROWS, SUM(E.AMOUNT) AS TOTAL
FROM EVENTS_BY_DATE E
JOIN CUSTOMER_VERSIONS C ON E.CUSTOMER_ID = C.CUSTOMER_ID
WHERE E.EVENT_DATE >= DATE '2025-01-01' AND E.EVENT_DATE < DATE '2025-01-08';

-- Latest-version join. Counts match the baseline, but the region is wrong.
WITH LATEST_CUSTOMERS AS (
  SELECT CUSTOMER_ID, REGION
  FROM CUSTOMER_VERSIONS
  QUALIFY ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID ORDER BY VALID_FROM DESC) = 1
)
SELECT C.REGION, COUNT(*) AS JOINED_ROWS, SUM(E.AMOUNT) AS TOTAL
FROM EVENTS_BY_DATE E
JOIN LATEST_CUSTOMERS C ON E.CUSTOMER_ID = C.CUSTOMER_ID
WHERE E.EVENT_DATE >= DATE '2025-01-01' AND E.EVENT_DATE < DATE '2025-01-08'
GROUP BY C.REGION;

-- Date-aware join. Each sale matches the version in effect on its date.
SELECT C.REGION, COUNT(*) AS JOINED_ROWS, SUM(E.AMOUNT) AS TOTAL
FROM EVENTS_BY_DATE E
JOIN CUSTOMER_VERSIONS C
  ON E.CUSTOMER_ID = C.CUSTOMER_ID
 AND E.EVENT_DATE >= C.VALID_FROM
 AND E.EVENT_DATE < C.VALID_TO
WHERE E.EVENT_DATE >= DATE '2025-01-01' AND E.EVENT_DATE < DATE '2025-01-08'
GROUP BY C.REGION;

ALTER SESSION UNSET USE_CACHED_RESULT;
ALTER SESSION UNSET QUERY_TAG;
