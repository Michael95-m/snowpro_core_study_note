-- Run in a fresh session in your main account.
-- First run: 100000 rows per sales table. Main run: change ROWCOUNT to 5000000.
-- Optional larger run: change ROWCOUNT to 20000000.
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS PERF_LAB_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  ENABLE_QUERY_ACCELERATION = FALSE;

CREATE TRANSIENT DATABASE IF NOT EXISTS PERF_LAB
  DATA_RETENTION_TIME_IN_DAYS = 0;
CREATE SCHEMA IF NOT EXISTS PERF_LAB.LAB;

USE WAREHOUSE PERF_LAB_WH;
USE DATABASE PERF_LAB;
USE SCHEMA LAB;

CREATE OR REPLACE TABLE EVENTS_INTERLEAVED AS
WITH IDS AS (
  SELECT ROW_NUMBER() OVER (ORDER BY SEQ8()) AS EVENT_ID
  FROM TABLE(GENERATOR(ROWCOUNT => 100000))
)
SELECT
  EVENT_ID,
  DATEADD('day', MOD(EVENT_ID - 1, 365), DATE '2025-01-01') AS EVENT_DATE,
  MOD(EVENT_ID - 1, 10000) + 1 AS CUSTOMER_ID,
  MOD(EVENT_ID - 1, 100) + 1 AS AMOUNT,
  SHA2(TO_VARCHAR(EVENT_ID), 512) ||
    SHA2(TO_VARCHAR(EVENT_ID) || ':payload', 512) AS EVENT_PAYLOAD
FROM IDS
ORDER BY EVENT_ID;

CREATE OR REPLACE TABLE EVENTS_BY_DATE AS
SELECT EVENT_ID, EVENT_DATE, CUSTOMER_ID, AMOUNT, EVENT_PAYLOAD
FROM EVENTS_INTERLEAVED
ORDER BY EVENT_DATE, EVENT_ID;

SELECT 'INTERLEAVED' AS LAYOUT, COUNT(*) AS EVENT_COUNT, SUM(AMOUNT) AS TOTAL,
       MIN(EVENT_DATE) AS FIRST_DATE, MAX(EVENT_DATE) AS LAST_DATE
FROM EVENTS_INTERLEAVED
UNION ALL
SELECT 'BY_DATE', COUNT(*), SUM(AMOUNT), MIN(EVENT_DATE), MAX(EVENT_DATE)
FROM EVENTS_BY_DATE;
