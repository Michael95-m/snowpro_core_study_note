-- Run each pair back-to-back on the same running warehouse.
USE ROLE SYSADMIN;
USE WAREHOUSE PERF_LAB_WH;
USE DATABASE PERF_LAB;
USE SCHEMA LAB;

ALTER SESSION SET USE_CACHED_RESULT = FALSE;
ALTER SESSION SET QUERY_TAG = 'PERF_LAB_WAREHOUSE_CACHE';

SELECT COUNT(*) AS EVENT_COUNT, SUM(AMOUNT) AS TOTAL
FROM EVENTS_BY_DATE
WHERE EVENT_DATE >= DATE '2025-04-01' AND EVENT_DATE < DATE '2025-07-01';

SELECT COUNT(*) AS EVENT_COUNT, SUM(AMOUNT) AS TOTAL
FROM EVENTS_BY_DATE
WHERE EVENT_DATE >= DATE '2025-04-01' AND EVENT_DATE < DATE '2025-07-01';

-- Both queries execute. Compare how much scanned data came from local cache.
ALTER SESSION SET USE_CACHED_RESULT = TRUE;
ALTER SESSION SET QUERY_TAG = 'PERF_LAB_RESULT_CACHE';

SELECT COUNT(*) AS EVENT_COUNT, SUM(AMOUNT) AS TOTAL
FROM EVENTS_BY_DATE
WHERE EVENT_DATE >= DATE '2025-07-01' AND EVENT_DATE < DATE '2025-08-01';

SELECT COUNT(*) AS EVENT_COUNT, SUM(AMOUNT) AS TOTAL
FROM EVENTS_BY_DATE
WHERE EVENT_DATE >= DATE '2025-07-01' AND EVENT_DATE < DATE '2025-08-01';

-- Compare query profiles to see whether Snowflake reused the final result.
ALTER SESSION UNSET USE_CACHED_RESULT;
ALTER SESSION UNSET QUERY_TAG;
