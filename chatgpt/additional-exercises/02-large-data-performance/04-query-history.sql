-- Run in the same session as exercises 01 through 03.
USE ROLE SYSADMIN;
USE WAREHOUSE PERF_LAB_WH;

SELECT START_TIME, QUERY_TAG, QUERY_ID,
       LEFT(QUERY_TEXT, 140) AS QUERY_PREVIEW,
       EXECUTION_TIME AS EXECUTION_MS, BYTES_SCANNED
FROM TABLE(PERF_LAB.INFORMATION_SCHEMA.QUERY_HISTORY_BY_SESSION(RESULT_LIMIT => 100))
WHERE QUERY_TYPE = 'SELECT'
  AND QUERY_TAG IN (
    'PERF_LAB_PRUNING', 'PERF_LAB_WAREHOUSE_CACHE',
    'PERF_LAB_RESULT_CACHE', 'PERF_LAB_JOIN'
  )
ORDER BY START_TIME;

