USE ROLE SYSADMIN;

-- Check state so this also works after the warehouse auto-suspends.
EXECUTE IMMEDIATE $$
DECLARE
  LAB_WH_STATE STRING;
BEGIN
  SHOW WAREHOUSES LIKE 'PERF_LAB_WH';
  SELECT MAX("state") INTO :LAB_WH_STATE
    FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
    WHERE "name" = 'PERF_LAB_WH';
  IF (LAB_WH_STATE = 'STARTED') THEN
    ALTER WAREHOUSE PERF_LAB_WH SUSPEND;
  END IF;
END;
$$;

ALTER SESSION UNSET USE_CACHED_RESULT;
