-- Run in your main account. This creates a small, isolated Iceberg lab.
-- Rerunning the CREATE OR REPLACE statement resets ORDERS and its Time Travel history.
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS ICEBERG_QUERY_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS ICEBERG_QUERY_LAB;
CREATE SCHEMA IF NOT EXISTS ICEBERG_QUERY_LAB.LAB;

USE WAREHOUSE ICEBERG_QUERY_WH;
USE DATABASE ICEBERG_QUERY_LAB;
USE SCHEMA LAB;

CREATE OR REPLACE ICEBERG TABLE ORDERS (
  ORDER_ID INT,
  CUSTOMER_ID INT,
  REGION STRING,
  ORDER_DATE DATE,
  STATUS STRING,
  AMOUNT DECIMAL(10, 2)
)
  CATALOG = 'SNOWFLAKE'
  EXTERNAL_VOLUME = 'SNOWFLAKE_MANAGED';

