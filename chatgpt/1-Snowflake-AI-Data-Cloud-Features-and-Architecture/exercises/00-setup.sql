-- Domain 1: run in a fresh lab session. Requires CREATE DATABASE/WAREHOUSE.
-- Creates only D1_STUDY objects. Queries consume warehouse credits.
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS D1_STUDY_WH
  WAREHOUSE_TYPE = STANDARD WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  ENABLE_QUERY_ACCELERATION = FALSE;
CREATE DATABASE IF NOT EXISTS D1_STUDY;
CREATE SCHEMA IF NOT EXISTS D1_STUDY.LAB;
USE WAREHOUSE D1_STUDY_WH;
USE DATABASE D1_STUDY;
USE SCHEMA LAB;

CREATE OR REPLACE TABLE ORDERS (
  ORDER_ID NUMBER, CUSTOMER_ID NUMBER, REGION STRING,
  AMOUNT NUMBER(12,2), ORDER_DATE DATE
);
INSERT INTO ORDERS VALUES
  (1,10,'APAC',100,'2026-01-01'),
  (2,10,'APAC',50,'2026-01-02'),
  (3,20,'EMEA',200,'2026-01-02'),
  (4,20,'EMEA',75,'2026-01-03'),
  (5,30,'APAC',25,'2026-01-03'),
  (6,40,'AMER',300,'2026-01-04');
SELECT COUNT(*) AS ORDER_COUNT, SUM(AMOUNT) AS TOTAL_AMOUNT FROM ORDERS;
-- Expected: 6 rows; total 750. APAC 175, EMEA 275, AMER 300.
SELECT CURRENT_ROLE(), CURRENT_WAREHOUSE(), CURRENT_DATABASE(), CURRENT_SCHEMA();
