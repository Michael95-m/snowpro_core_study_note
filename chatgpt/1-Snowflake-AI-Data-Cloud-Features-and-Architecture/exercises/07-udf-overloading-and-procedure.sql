-- Optional Domain 1 extension. Run 00-setup.sql first.
-- Compare a scalar UDF (usable in SELECT) with a procedure (called with CALL).
USE ROLE SYSADMIN;
USE WAREHOUSE D1_STUDY_WH;
USE DATABASE D1_STUDY;
USE SCHEMA LAB;

-- Same function name, different required argument count: two signatures.
CREATE OR REPLACE FUNCTION D1_STUDY.LAB.NORMALIZE_LABEL(V STRING)
  RETURNS STRING LANGUAGE SQL
  AS $$ UPPER(TRIM(V)) $$;

CREATE OR REPLACE FUNCTION D1_STUDY.LAB.NORMALIZE_LABEL(V STRING, PREFIX STRING)
  RETURNS STRING LANGUAGE SQL
  AS $$ PREFIX || ':' || UPPER(TRIM(V)) $$;

SELECT
  D1_STUDY.LAB.NORMALIZE_LABEL('  apac  ') AS ONE_ARGUMENT,
  D1_STUDY.LAB.NORMALIZE_LABEL('  apac  ', 'region') AS TWO_ARGUMENTS;
-- Expected: APAC and region:APAC.

-- A UDF can run once per input row inside a query.
SELECT ORDER_ID, D1_STUDY.LAB.NORMALIZE_LABEL(REGION) AS REGION_LABEL
FROM D1_STUDY.LAB.ORDERS
ORDER BY ORDER_ID;
-- Expected: six rows. The UDF does not modify ORDERS.

CREATE OR REPLACE TABLE D1_STUDY.LAB.LABEL_AUDIT (
  ORDER_ID NUMBER,
  LABEL STRING
);

CREATE OR REPLACE PROCEDURE D1_STUDY.LAB.SAVE_ORDER_LABEL(P_ORDER_ID NUMBER)
  RETURNS STRING
  LANGUAGE SQL
  EXECUTE AS CALLER
AS
$$
BEGIN
  INSERT INTO D1_STUDY.LAB.LABEL_AUDIT (ORDER_ID, LABEL)
  SELECT ORDER_ID, D1_STUDY.LAB.NORMALIZE_LABEL(REGION)
  FROM D1_STUDY.LAB.ORDERS
  WHERE ORDER_ID = :P_ORDER_ID;
  RETURN 'saved';
END;
$$;

CALL D1_STUDY.LAB.SAVE_ORDER_LABEL(1);
SELECT ORDER_ID, LABEL FROM D1_STUDY.LAB.LABEL_AUDIT ORDER BY ORDER_ID;
-- Expected after one call: (1, APAC). The procedure performs DML.
-- Calling it again inserts another audit row; this is intentional.

